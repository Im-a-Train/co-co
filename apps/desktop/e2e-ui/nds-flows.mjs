/** NDS flows of the UI harness (imported by run.mjs). Mock IPC returns an invented aggregate. */

export async function ndsFlows({ page, step, go, shot, BASE }) {
  const text = () => page.evaluate(() => document.body.innerText)

  await step('flow: settings shows the NDS section and enables it', async () => {
    await page.goto(`${BASE}#/einstellungen`)
    await page.waitForSelector('[data-testid="nds-settings"]', { timeout: 8000 })
    await page.waitForTimeout(600)
    const sw = page.getByTestId('nds-enable').locator('input')
    if (!(await sw.isChecked())) await sw.check()
    await page.waitForTimeout(400)
    await shot(page, 'flow-nds-settings')
    const t = await text()
    if (!/Rote Zone/i.test(t)) throw new Error('red zone text missing')
    if (!/keine öffentliche Schnittstelle/i.test(t)) throw new Error('unofficial hint missing')
    const status = await page.getByTestId('nds-status').innerText()
    if (!/verbunden/i.test(status)) throw new Error('status chip: ' + status)
    if (!/SESSION/.test(await text())) throw new Error('cookie names missing')
  })

  await step('flow: NDS diagnosis shows endpoints', async () => {
    await page.getByTestId('settings-diagnostics-toggle').click()
    await page.waitForSelector('[data-testid="nds-diag"]', { timeout: 5000 })
    await page.locator('[data-testid="nds-diag"] input').first().fill('camp-9001')
    await page.getByTestId('nds-probe').click()
    await page.waitForSelector('[data-testid="nds-probe-result"]', { timeout: 5000 })
    await shot(page, 'flow-nds-probe')
  })

  await step('flow: settings detects the own NDS person and loads the coach profile (M21)', async () => {
    await page.goto(`${BASE}#/einstellungen`)
    await page.waitForSelector('[data-testid="nds-person"]', { timeout: 8000 })
    await page.getByTestId('nds-personid-detect').click()
    await page.waitForFunction(() => document.querySelector('[data-testid="nds-personid"] input')?.value === '424242', null, { timeout: 5000 })
    await page.getByTestId('nds-profile-load').click()
    await page.waitForSelector('[data-testid="nds-profile"]', { timeout: 5000 })
    await page.getByTestId('nds-profile-offers-toggle').click()
    await page.getByTestId('nds-profile-offers').waitFor({ timeout: 3000 })
    const t = await text()
    if (!/Pfadi Musterhausen/.test(t)) throw new Error('organisation missing in the coach profile')
    if (!/2026: 1/.test(t)) throw new Error('finished offers per year missing')
    await page.getByTestId('nds-person').scrollIntoViewIfNeeded()
    await shot(page, 'flow-nds-settings-profile')
  })

  await step('flow: Lager-Angaben pick NDS camp, load, adopt, badge', async () => {
    await go('angaben', 'flow-nds-card')
    await page.waitForSelector('[data-testid="nds-card"]', { timeout: 8000 })
    await page.waitForTimeout(500)
    await page.getByTestId('nds-pick').click({ timeout: 5000 })
    await page.getByTestId('nds-camp-camp-9001').waitFor({ timeout: 5000 })
    // M21: the ranked picker marks exactly one candidate as «Vorschlag» (the coach still clicks).
    if ((await page.getByTestId('nds-suggested').count()) !== 1) throw new Error('picker should show exactly one «Vorschlag» badge')
    await shot(page, 'flow-nds-picker')
    await page.getByTestId('nds-camp-camp-9001').click({ timeout: 5000 })
    await page.waitForTimeout(500)
    const linkText = await page.getByTestId('nds-link').innerText()
    if (!/Musterstufe · Angebot 999001 \(/.test(linkText) || /camp-9001/.test(linkText)) throw new Error('link line should name the camp, not the id: ' + linkText)
    await shot(page, 'flow-nds-linked')
    await page.getByTestId('nds-refresh').click({ timeout: 5000 })
    await page.waitForSelector('[data-testid="nds-summary"]', { timeout: 8000 })
    const stand = await page.getByTestId('nds-stand').innerText()
    if (!/Stand NDS: \d{2}\.\d{2}\.\d{4} \d{2}:\d{2}/.test(stand)) throw new Error('bad Stand: ' + stand)
    const t = await text()
    if (!/bewilligt am 03\.05\.2026 \(angemeldet spätestens an diesem Tag\)/.test(t)) throw new Error('approval chip missing')
    if (/CHILD:|ADOLESCENT:/.test(t)) throw new Error('raw role codes in the NDS card')
    if (!/offener Anwesenheitskontrolle/.test(t)) throw new Error('AWK summary missing')
    await shot(page, 'flow-nds-loaded')

    // M21: attendance, camp details and protocol sections
    for (const id of ['nds-attendance', 'nds-details', 'nds-protocol']) {
      await page.waitForSelector(`[data-testid="${id}"]`, { timeout: 5000 })
    }
    if (!/Doppelbuchungen: 2 Teilnehmende/.test(t)) throw new Error('double bookings missing')
    if (!/999123/.test(t)) throw new Error('overlap offer number missing')
    if (!/Bewilligung mit Vorbehalt/.test(t)) throw new Error('details flags missing')
    if (!/Mindestens ein Leitender/.test(t)) throw new Error('minimum requirement message missing')
    if (!/CHF 1’432\.50/.test(t)) throw new Error('subsidies missing')
    if (!/20\.04\.2026/.test(t) || !/NDS-Verlauf/.test(t)) throw new Error('protocol missing')
    await page.getByTestId('nds-attendance-dates-toggle').click()
    await page.getByTestId('nds-attendance-dates').waitFor({ timeout: 3000 })
    await page.getByTestId('nds-attendance').scrollIntoViewIfNeeded()
    await shot(page, 'flow-nds-attendance')
    await page.getByTestId('nds-details').scrollIntoViewIfNeeded()
    await shot(page, 'flow-nds-details')
    await page.getByTestId('nds-protocol').scrollIntoViewIfNeeded()
    await shot(page, 'flow-nds-protocol')

    await page.getByTestId('nds-adopt-open').click()
    await page.waitForSelector('[data-testid="nds-adopt"]', { timeout: 5000 })
    await page.waitForTimeout(400)
    await shot(page, 'flow-nds-adopt-dialog')
    if (!(await page.getByTestId('nds-adopt-row-ndsRegisteredOn').innerText()).includes('laut NDS-Verlauf')) throw new Error('adopt hint for the protocol date missing')
    const check = page.getByTestId('nds-adopt-check-ndsRegistered').locator('input')
    if (!(await check.isChecked())) await check.check()
    await page.getByTestId('nds-adopt-apply').click()
    // The NDS deadline fields no longer live in Angaben (they are edited in Checkliste), so there is no
    // badge here any more: wait for the dialog to close and the autosave-free adopt save to finish.
    await page.waitForSelector('[data-testid="nds-adopt"]', { state: 'detached', timeout: 5000 })
    await page.waitForTimeout(800)
    await shot(page, 'flow-nds-adopted')
    // Checkliste shows the adopted NDS deadline values with their «NDS» badge (ADR 0007)
    await go('checkliste', 'flow-nds-checklist')
    await page.waitForSelector('[data-testid="camp-deadlines-card"]', { timeout: 8000 })
    if (!(await page.locator('[data-testid="camp-deadline"] [data-testid="nds-badge"]').count())) throw new Error('NDS badge missing in Checkliste')
    await page.getByTestId('camp-deadlines-card').scrollIntoViewIfNeeded()
    await shot(page, 'flow-nds-checklist')
  })
  await step('flow: Fristen loads the own recognitions into the radar (M21, memory only)', async () => {
    await page.goto(`${BASE}#/fristen`)
    await page.waitForSelector('[data-testid="deadlines-summary"]', { timeout: 8000 })
    const load = page.getByTestId('nds-recognitions-load')
    await load.waitFor({ timeout: 5000 })
    await load.click()
    await page.getByTestId('nds-recognitions-stand').waitFor({ timeout: 5000 })
    if (await page.getByTestId('nds-recognitions-error').count()) throw new Error('recognitions error')
    // «Später» is collapsed by default: open every group header that is closed.
    for (const h of await page.locator('[data-testid^="group-head-"][aria-expanded="false"]').all()) await h.click()
    await page.waitForTimeout(400)
    const t = await text()
    if (!/J\+S-Coach Lagersport\/Trekking: Anerkennung läuft ab/.test(t)) throw new Error('recognition deadline not in radar')
    if (!/Anerkennung sistiert/.test(t)) throw new Error('omitted recognition not marked')
    await shot(page, 'flow-radar-nds-recognitions')
  })
}
